/*
  Prepares the web interface's static files.

  The PHP Wallos repository already holds the stylesheets, scripts, fonts and
  images the interface uses; this copies them into worker/public/, which
  Workers Static Assets serves (see "assets" in wrangler.jsonc). It also
  regenerates src/ui/icons.ts from the SVG markup the PHP templates included.

  node scripts/build-assets.ts     (runs before dev, test and deploy)
*/

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const worker = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(worker, "..");
const out = join(worker, "public");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

// Never ship server code, user uploads or repository clutter as static files.
const skip = (path: string) => {
  const rel = relative(repo, path).split(sep).join("/");
  return (
    rel.endsWith(".php") ||
    rel.endsWith("Thumbs.db") ||
    rel.startsWith("images/screenshots") ||
    (rel.startsWith("images/uploads/logos/") && rel !== "images/uploads/logos/wallos.png")
  );
};

for (const dir of ["styles", "scripts", "images", "webfonts"]) {
  cpSync(join(repo, dir), join(out, dir), { recursive: true, filter: (src) => !skip(src) });
}
for (const file of ["robots.txt"]) {
  if (existsSync(join(repo, file))) cpSync(join(repo, file), join(out, file));
}

// SVG icons the PHP templates pulled in with include "images/siteicons/svg/...php".
const svgRoot = join(repo, "images", "siteicons", "svg");
const icons: [string, string][] = [];
const walk = (dir: string) => {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith(".php")) {
      const svg = /<svg[\s\S]*<\/svg>/.exec(readFileSync(path, "utf8"))?.[0];
      if (svg) icons.push([relative(svgRoot, path).slice(0, -4).split(sep).join("/"), svg.trim()]);
    }
  }
};
walk(svgRoot);
writeFileSync(
  join(worker, "src", "ui", "icons.ts"),
  [
    "/*",
    "  SVG icons the PHP templates included from images/siteicons/svg/*.php.",
    "  Generated by scripts/build-assets.ts from the PHP sources; do not edit.",
    "*/",
    "",
    "export const ICONS = {",
    ...icons.map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`),
    "} as const;",
    "",
    "export type IconName = keyof typeof ICONS;",
    "",
  ].join("\n"),
);

let count = 0;
const countFiles = (dir: string) => readdirSync(dir).forEach((n) => (statSync(join(dir, n)).isDirectory() ? countFiles(join(dir, n)) : count++));
countFiles(out);
console.log(`public/: ${count} files; src/ui/icons.ts: ${icons.length} icons`);
